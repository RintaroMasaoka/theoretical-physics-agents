#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const catalogPath = "literature/catalog.jsonl";
const outputPath = "literature/reading_list.md";

function readCatalog(path) {
  if (!existsSync(path)) {
    throw new Error(`${path} does not exist`);
  }
  return readFileSync(path, "utf8")
    .split(/\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line, index) => {
      try {
        return JSON.parse(line);
      } catch (error) {
        throw new Error(`${path}:${index + 1}: ${error.message}`);
      }
    });
}

function escapeCell(value) {
  return String(value ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
}

function relativeRepoLink(path) {
  if (!path) return "";
  if (path.startsWith("literature/")) return path.slice("literature/".length);
  if (path.startsWith(".logs/")) return `../${path}`;
  return path;
}

function literaturePath(relativePath) {
  return `literature/${relativePath.replace(/\/$/, "")}`;
}

function arxivAbsUrl(id) {
  return `https://arxiv.org/abs/${encodeURIComponent(id).replace("%2F", "/")}`;
}

function arxivPdfUrl(id) {
  return `https://arxiv.org/pdf/${encodeURIComponent(id).replace("%2F", "/")}`;
}

function sourceLabel(source) {
  return source === "arxiv" ? "arXiv" : source;
}

function link(label, target) {
  return `[${escapeCell(label)}](${target})`;
}

function notesLinks(notes) {
  return (notes ?? []).map((note, index) => link(`note ${index + 1}`, relativeRepoLink(note)));
}

function sourceNoteLink(record) {
  return record.source_note ? [link("source note", relativeRepoLink(record.source_note))] : [];
}

function sourceLinks(record) {
  const links = [];
  if (record.source === "arxiv") {
    links.push(link("abstract", arxivAbsUrl(record.id)));
    links.push(link("arXiv PDF", arxivPdfUrl(record.id)));
  }
  if (record.fetch?.path) {
    const localDir = relativeRepoLink(record.fetch.path);
    links.push(link("local files", localDir));
    const fullLocalDir = literaturePath(localDir);
    if (existsSync(`${fullLocalDir}/paper.pdf`)) {
      links.push(link("local PDF", `${localDir}paper.pdf`));
    }
    if (existsSync(`${fullLocalDir}/cite.bib`)) {
      links.push(link("BibTeX", `${localDir}cite.bib`));
    }
    if (existsSync(fullLocalDir)) {
      const sourceFiles = readdirSync(fullLocalDir)
        .filter((name) => name.endsWith(".tex") || name === "source")
        .sort();
      sourceFiles.forEach((name, index) => {
        links.push(link(sourceFiles.length === 1 ? "source" : `source ${index + 1}`, `${localDir}${encodeURI(name)}`));
      });
    }
  }
  links.push(...sourceNoteLink(record));
  links.push(...notesLinks(record.reading_notes));
  return links.join(" · ");
}

function paperCell(record) {
  const title = record.source === "arxiv"
    ? link(record.title, arxivAbsUrl(record.id))
    : escapeCell(record.title);
  return `${title}<br>${escapeCell(record.authors.join(", "))} (${escapeCell(record.year)})`;
}

function rationale(record) {
  return (record.selection_sources ?? [])
    .map((source) => {
      const prefix = source.kind === "query"
        ? `query: \`${source.value}\``
        : `${source.kind}: ${source.value}`;
      const detail = source.abstract_quote
        ? ` — "${source.abstract_quote}"`
        : source.note
          ? ` — ${source.note}`
          : "";
      return `${prefix}${detail}`;
    })
    .join("<br>");
}

function render(records) {
  const rows = records.map((record) => [
    paperCell(record),
    escapeCell(record.status),
    escapeCell(sourceLabel(record.source)),
    sourceLinks(record),
    rationale(record),
  ]);

  return [
    "# Reading List",
    "",
    `Generated from \`${catalogPath}\`. Do not edit this file by hand; update the catalog and run \`node .scripts/render-reading-list.mjs\`.`,
    "",
    "| Paper | Status | Source | Links | Why it is here |",
    "|---|---|---|---|---|",
    ...rows.map((row) => `| ${row.join(" | ")} |`),
    "",
  ].join("\n");
}

const records = readCatalog(catalogPath);
writeFileSync(outputPath, render(records));
console.log(`rendered ${outputPath} from ${records.length} catalog records`);
